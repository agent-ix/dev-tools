#!/usr/bin/env python3
"""Generate vale/config/scripts/*.tengo from one template.

Vale script rules cannot import a shared file, so every script carries the same
mask code. This generator is the single source: edit RULES or TEMPLATE here and
run `python3 scripts/gen_vale_scripts.py`. `--check` exits 1 when a committed
script differs from the generated one. Standard library only.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List, Tuple

OUT = Path(__file__).resolve().parent.parent / "vale" / "config" / "scripts"

DELIM = r"[ \t]*:?-+:?[ \t]*"
# (patterns, dedupe matches that start on the same offset)
RULES: Dict[str, Tuple[List[str], bool]] = {
    # A table whose delimiter row has five or more cells, with or without outer pipes.
    # The match starts on the header row, so the line agrees with docs_lint.py.
    "table-too-wide": ([r"(?m)^[^\n]*\|[^\n]*\n[ \t]*\|?" + DELIM + r"(?:\|" + DELIM + r"){4,}\|?[ \t]*$"], True),
    # A table row that holds an inline code span of 30 or more characters.
    "table-code-cell-long": ([
        r"(?m)^[^\n`]*\|[^\n`]*`[^`|\n]{30,}`",
        r"(?m)^[^\n`|]*`[^`|\n]{30,}`[^\n`]*\|",
    ], True),
    # Edit the prefixes (default: qsl, tl) to the internal crate prefixes of your repository.
    "crate-name-in-prose": ([r"\b(qsl|tl)-[a-z0-9-]+\b"], True),
    "source-path-in-prose": ([
        r"`[A-Za-z0-9_.-]+/(src|tests)/[^`\s]+`",
        r"`tests/[^`\s]+`",
        r"`src/[^`\s]+\.(rs|ts|py)`",
    ], True),
    "test-name-in-prose": ([
        r"\btc_[0-9]+\w*",
        r"\b(an?|the)_[a-z]+_[a-z_]{12,}\b",
        r"\b(mirrors|see|exercised by|verified by) `[^`]*(tests/|test_|tc_)[^`]*`",
    ], True),
    "no-command-runs": ([
        r"\bNo `[^`]+` (command|subcommand) (runs|evaluates|executes|checks|reads)\b",
        r"\bNo (command|subcommand) (runs|evaluates|executes|checks)\b",
    ], True),
}

TEMPLATE = r'''// GENERATED by scripts/gen_vale_scripts.py. Do not edit; edit the generator.
// Matches outside: frontmatter, fenced code (same character, closing run at least as long),
// indented code, HTML comments, link targets and bare URLs.
text := import("text")
patterns := [__PATTERNS__]

ranges := []
add := func(b, e) { ranges = append(ranges, {begin: b, end: e}) }

fm := text.re_find("(?s)\\A---[ \\t]*\\r?\\n.*?\\r?\\n---[ \\t]*(\\r?\\n|\\z)", scope, 1)
if fm != undefined {
  add(fm[0][0].begin, fm[0][0].end)
}
skips := ["(?s)<!--.*?-->", "\\]\\([^)]*\\)", "<https?://[^>\\s]*>", "https?://[^\\s)>\\]]+"]
for p in skips {
  m := text.re_find(p, scope, -1)
  if m != undefined {
    for i := 0; i < len(m); i++ {
      add(m[i][0].begin, m[i][0].end)
    }
  }
}

lines := text.split(scope, "\n")
off := 0
fence_ch := ""
fence_len := 0
fence_begin := 0
in_indent := false
ind_begin := 0
prev_blank := true
in_list := false
for i := 0; i < len(lines); i++ {
  line := lines[i]
  next := off + len(line) + 1
  blank := text.re_match("^\\s*$", line)
  indented := text.re_match("^(    |\\t)\\S", line)
  if fence_ch != "" {
    c := text.re_find("^[ \\t]*(`{3,}|~{3,})[ \\t\\r]*$", line, 1)
    if c != undefined && text.has_prefix(c[0][1].text, fence_ch) && len(c[0][1].text) >= fence_len {
      add(fence_begin, next)
      fence_ch = ""
    }
  } else {
    if in_indent && !indented && !blank {
      add(ind_begin, off)
      in_indent = false
    }
    o := text.re_find("^[ \\t]*(`{3,}|~{3,})(.*)$", line, 1)
    if o != undefined && !(text.has_prefix(o[0][1].text, "`") && text.contains(o[0][2].text, "`")) {
      fence_ch = text.substr(o[0][1].text, 0, 1)
      fence_len = len(o[0][1].text)
      fence_begin = off
    } else if !in_indent && indented && prev_blank && !in_list {
      in_indent = true
      ind_begin = off
    }
    if !blank && !indented {
      in_list = text.re_match("^\\s{0,3}([-*+]|[0-9]+[.)])\\s", line)
    }
  }
  prev_blank = blank
  off = next
}
if fence_ch != "" {
  add(fence_begin, len(scope))
}
if in_indent {
  add(ind_begin, len(scope))
}

matches := []
seen := {}
for p in patterns {
  m := text.re_find(p, scope, -1)
  if m != undefined {
    for i := 0; i < len(m); i++ {
      c := m[i][0]
      inside := false
      for j := 0; j < len(ranges); j++ {
        if c.begin >= ranges[j].begin && c.begin < ranges[j].end {
          inside = true
        }
      }
      key := string(c.begin)
      if !inside && (!__DEDUPE__ || seen[key] == undefined) {
        seen[key] = true
        matches = append(matches, {begin: c.begin, end: c.end})
      }
    }
  }
}
'''


def render(name: str) -> str:
    patterns, dedupe = RULES[name]
    body = ", ".join(json.dumps(p) for p in patterns)
    return TEMPLATE.replace("__PATTERNS__", body).replace("__DEDUPE__", "true" if dedupe else "false")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="exit 1 if a committed script is stale")
    args = ap.parse_args()
    stale = 0
    for name in RULES:
        path = OUT / (name + ".tengo")
        want = render(name)
        have = path.read_text(encoding="utf-8") if path.exists() else None
        if have != want:
            if args.check:
                print("%s: stale; run scripts/gen_vale_scripts.py" % path)
                stale = 1
            else:
                path.write_text(want, encoding="utf-8")
    return stale


if __name__ == "__main__":
    sys.exit(main())
